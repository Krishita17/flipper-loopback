def _page(title: str, meta: str, body: str) -> str:
    t = html.escape(title)
    return (
        "<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>"
        "<meta name='viewport' content='width=device-width,initial-scale=1'>"
        f"<title>{t}</title><style>{_CSS}</style></head><body><main>"
        f"<h1><span>■</span> {t}</h1><div class='meta'>{meta}</div>{body}"
        "<footer>Generated by flipper-loopback · "
        "https://github.com/Krishita17/flipper-loopback</footer></main></body></html>"
    )


def _card(label: str, value: str) -> str:
    return f"<div class='card'><b>{html.escape(label)}</b><span class='n'>{value}</span></div>"


def junit_html(results: dict[str, CaseResult], title: str = "HIL results") -> str:
    fw = next((r.properties.get("dut_firmware") for r in results.values() if r.properties), "?")
    counts = {
        k: sum(r.status == k for r in results.values()) for k in ("pass", "fail", "error", "skip")
    }
    subs = sorted({r.subsystem for r in results.values()})
    cards = (
        _card("passed", str(counts["pass"]))
        + _card("failed", str(counts["fail"] + counts["error"]))
        + _card("skipped", str(counts["skip"]))
        + _card("subsystems", str(len(subs)))
    )
    rows = []
    for key in sorted(results, key=lambda k: (results[k].subsystem, k)):
        r = results[key]
        props = r.properties
        detail = ""
        if r.message:
            detail = (
                f"<details><summary>{html.escape(first_line(r.message, 140))}</summary>"
                f"<pre>{html.escape(r.message[:4000])}</pre></details>"
            )
        rows.append(
            f"<tr><td><code>{html.escape(key)}</code>{detail}</td>"
            f"<td>{html.escape(r.subsystem)}</td>"
            f"<td><span class='chip {r.status}'>{r.status}</span></td>"
            f"<td class='num'>{html.escape(props.get('duration_s', ''))}</td>"
            f"<td>{html.escape(props.get('decodes', ''))}</td></tr>"
        )
    table = (
        "<div class='wrap'><table><thead><tr><th>Case</th><th>Subsystem</th><th>Status</th>"
        "<th>Seconds</th><th>Decoded</th></tr></thead><tbody>"
        + ("".join(rows) or "<tr><td colspan='5'>No hardware cases in this report.</td></tr>")
        + "</tbody></table></div>"
    )
    meta = f"DUT firmware {html.escape(fw or '?')} · generated {time.strftime('%Y-%m-%d %H:%M')}"
    return _page(title, meta, f"<div class='cards'>{cards}</div>{table}")


def soak_html(report: SoakReport, title: str = "Soak report") -> str:
    live = [f for f in report.fixtures if not f.skipped_reason]
    flaky = [f for f in live if f.flaky]
    runs = sum(f.runs for f in live)
    passed = sum(f.passed for f in live)
    rate = f"{passed / runs:.0%}" if runs else "n/a"
    cards = (
        _card("cases", str(len(live)))
        + _card("runs", str(runs))
        + _card("pass rate", rate)
        + _card("flaky", str(len(flaky)))
    )
    rows = []
    for f in report.fixtures:
        if f.skipped_reason:
            rows.append(
                f"<tr><td><code>{html.escape(f.case_id)}</code></td>"
                f"<td>{html.escape(f.subsystem)}</td><td colspan='5'>"
                f"<span class='chip skip'>skipped</span> {html.escape(f.skipped_reason)}</td></tr>"
            )
            continue
        status = "pass" if f.pass_rate == 1 else ("skip" if f.flaky else "fail")
        label = "stable" if status == "pass" else ("flaky" if f.flaky else "failing")
        budget = f.suggested_budget_s()
        decodes = "; ".join(f"{k} ×{v}" for k, v in f.distinct_decodes.items())
        rows.append(
            f"<tr><td><code>{html.escape(f.case_id)}</code></td>"
            f"<td>{html.escape(f.subsystem)}</td>"
            f"<td><span class='chip {status}'>{label}</span></td>"
            f"<td class='num'>{f.passed}/{f.runs}</td>"
            f"<td class='num'>{(f.p(0.5) or 0):.2f} / {(f.p(0.95) or 0):.2f}</td>"
            f"<td class='num'>{'' if budget is None else f'{budget:.1f}'}</td>"
            f"<td>{html.escape(decodes)}</td></tr>"
        )
    table = (
        "<div class='wrap'><table><thead><tr><th>Case</th><th>Subsystem</th><th>Verdict</th>"
        "<th>Pass</th><th>p50 / p95 s</th><th>Budget?</th><th>Decodes</th></tr></thead><tbody>"
        + "".join(rows)
        + "</tbody></table></div>"
    )
    meta = (
        f"{report.runs_per_fixture} runs per case · DUT fw {html.escape(report.dut_fw)} · "
        f"emitter fw {html.escape(report.emitter_fw)} · {html.escape(report.started)}"
    )
    return _page(title, meta, f"<div class='cards'>{cards}</div>{table}")
